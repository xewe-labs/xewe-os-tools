"""``xewe build``: XeWeBuildInfo generation, arduino-cli compile, ``build/builds/<chip>/out/`` (SPEC §7)."""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import re
import shlex
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from xewe import __version__
from xewe.build import chips
from xewe.env import arduino, config, fetch
from xewe.env.project import Paths
from xewe.modules.lockfile import Lock
from xewe.report import EXIT_FAIL, EXIT_NOT_SETUP, EXIT_OK, EXIT_USAGE, XeWeError, log, result, verbose

DEFINE_KEY_RE = re.compile(r"^[A-Za-z_]\w*$")
SIZE_RE = re.compile(r"Sketch uses (\d+) bytes(?: \((\d+)%\))?")
STAMP_NAME = "build.stamp"
SKETCH_SUFFIXES = (".ino", ".h", ".cpp", ".c", ".hpp")
MANIFEST_TEMPLATE = """{{
  "name": "{name}",
  "version": "{version}",
  "new_install_improv_wait_time": 0,
  "builds": [
    {{
      "chipFamily": "{family}",
      "parts": [
        {{ "path": "{binary}", "offset": 0 }}
      ]
    }}
  ]
}}
"""
LIBRARY_PROPERTIES = """name=XeWeBuildInfo
version=0.0.0
author=xewe build
maintainer=xewe build
sentence=Build information generated by xewe build; do not edit.
paragraph=PROJECT_NAME, BUILD_VERSION, BUILD_TIMESTAMP, BUILD_CHIP and --define values.
category=Other
url=https://github.com/xewe-labs/xewe-os-tools
architectures=*
"""


@dataclass
class BuildResult:
    """Outcome of one chip's build."""

    chip: str
    ok: bool
    binary: Path | None = None
    seconds: int = 0
    size: int | None = None
    warnings: int = 0
    percent: int | None = None


def project_name(p: Paths, lock: Lock) -> str:
    """``[project] name`` or the stem of the single .ino."""
    return lock.name or p.sketch_ino().stem


def binary_name(version: str, chip: str, name: str) -> str:
    """``<version>-<chip>-<project>.bin``."""
    return f"{version}-{chip}-{name}.bin"


def parse_defines(items: list[str]) -> dict[str, str]:
    """``KEY=VALUE`` pairs from ``--define`` (values verbatim)."""
    out: dict[str, str] = {}
    for item in items:
        key, sep, value = item.partition("=")
        if not sep or not DEFINE_KEY_RE.match(key):
            raise XeWeError(f"--define expects KEY=VALUE with a C identifier as KEY, got '{item}'", EXIT_USAGE)
        out[key] = value
    return out


def typed(value: str) -> Any:
    """meta.json typing of a define value (as the old release matrix): integers/true/false bare."""
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    if value in ("true", "false"):
        return value == "true"
    return value


def _now() -> str:
    return dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def stage_sketch(p: Paths) -> Path:
    """Sketch directory for arduino-cli: the root when its name equals the .ino stem, else a mirror.

    The mirror ``build/tmp/sketch/<stem>/`` holds the root's sketch files and ``src/``, copied with
    their mtimes so the compile cache stays warm.
    """
    ino = p.sketch_ino()
    if p.root.name == ino.stem:
        return p.root
    dest = p.sketch_mirror(ino.stem)
    shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir(parents=True)
    for f in p.root.iterdir():
        if f.is_file() and f.suffix in SKETCH_SUFFIXES:
            shutil.copy2(f, dest / f.name)
    if (p.root / "src").is_dir():
        shutil.copytree(p.root / "src", dest / "src", copy_function=shutil.copy2)
    return dest


def build_info_header(name: str, version: str, timestamp: str, chip: str, defines: dict[str, str]) -> str:
    """Contents of ``XeWeBuildInfo.h``."""
    lines = [
        "// generated by xewe build; do not edit",
        "#pragma once",
        f'#define PROJECT_NAME "{name}"',
        f'#define BUILD_VERSION "{version}"',
        f'#define BUILD_TIMESTAMP "{timestamp}"',
        f'#define BUILD_CHIP "{chip}"',
    ]
    lines += [f"#define {k} {v}" for k, v in defines.items()]
    return "\n".join(lines) + "\n"


def write_build_info(p: Paths, chip: str, header: str) -> Path:
    """Write the generated XeWeBuildInfo library for ``chip`` and return its directory."""
    lib = p.gen_dir(chip) / "XeWeBuildInfo"
    (lib / "src").mkdir(parents=True, exist_ok=True)
    (lib / "library.properties").write_text(LIBRARY_PROPERTIES, encoding="utf-8")
    (lib / "src" / "XeWeBuildInfo.h").write_text(header, encoding="utf-8")
    return lib


def cli_path(p: Paths, cfg: config.BuildConfig | None) -> Path:
    """arduino-cli to run: XEWE_ARDUINO_CLI, the recorded one, or the shared ``bin/arduino-cli-<version>``."""
    return arduino.cli_override() or (cfg.path(p, "arduino_cli") if cfg else None) or arduino.default_cli(p)


def _resolved_modules(p: Paths) -> list[str]:
    lock_file = p.modules_lock
    if not lock_file.is_file():
        return []
    return [line.split("|", 1)[0] for line in lock_file.read_text().splitlines() if line and not line.startswith("#")]


def _sources(p: Paths) -> list[Path]:
    files = [f for f in p.root.iterdir() if f.is_file() and f.suffix in SKETCH_SUFFIXES]
    files += [f for f in (p.lock, p.modules / "library.properties") if f.is_file()]
    for d in (p.root / "src", p.libraries, p.modules / "src"):
        if d.is_dir():
            files += [f for f in d.rglob("*") if f.is_file() and ".git" not in f.parts]
    return files


def build_key(chip_name: str, version: str, defines: dict[str, str]) -> str:
    """Hash of the build inputs that are not files: chip, FQBN (with board options), version, defines."""
    chip = chips.get(chip_name)
    inputs = {
        "chip": chip.name,
        "fqbn": chip.fqbn,
        "version": version,
        "defines": sorted(defines.items()),
    }
    return hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest()


def is_up_to_date(p: Paths, binary: Path, key: str | None = None) -> bool:
    """True when ``binary`` exists, is newer than every source file and was built with ``key``.

    ``key`` (from :func:`build_key`) is compared with ``build.stamp`` next to the binary, so a
    build with other ``--define`` values, version, chip or FQBN options is stale.
    """
    if not binary.is_file():
        return False
    if key is not None:
        stamp = binary.parent / STAMP_NAME
        if not stamp.is_file() or stamp.read_text(encoding="utf-8").strip() != key:
            return False
    built = binary.stat().st_mtime
    return all(f.stat().st_mtime <= built for f in _sources(p))


def parse_size(output: str) -> tuple[int | None, int | None]:
    """(bytes, percent of program storage) from arduino-cli's "Sketch uses N bytes (NN%)" line."""
    m = SIZE_RE.search(output)
    if not m:
        return None, None
    return int(m[1]), int(m[2]) if m[2] is not None else None


def _compile(argv: list[str], env_vars: dict[str, str], cwd: Path, log_path: Path) -> tuple[int, str]:
    """Run the compile, writing compile.log; ``--verbose`` streams it to stderr."""
    log.debug("$ %s", shlex.join(argv))
    try:
        proc = subprocess.Popen(argv, cwd=cwd, env=env_vars, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    except FileNotFoundError:
        raise XeWeError(f"{argv[0]} not found; run ./setup.sh", EXIT_NOT_SETUP) from None
    chunks: list[str] = []
    with log_path.open("w", encoding="utf-8") as logf:
        assert proc.stdout is not None
        for line in proc.stdout:
            logf.write(line)
            chunks.append(line)
            if verbose():
                sys.stderr.write(line)
    return proc.wait(), "".join(chunks)


def build_chip(
    p: Paths,
    lock: Lock,
    chip_name: str,
    defines: dict[str, str] | None = None,
    clean: bool = False,
    version: str | None = None,
    dry_run: bool = False,
) -> BuildResult:
    """Build one chip; on success ``build/builds/<chip>/out/`` holds the bin, manifest.json, meta.json."""
    chip = chips.get(chip_name)
    defines = defines or {}
    version = version or lock.version
    cfg = config.load(p) if dry_run else config.require(p)
    if not dry_run:
        for needed in (p.src_modules_h, p.modules / "library.properties"):
            if not needed.is_file():
                raise XeWeError(f"{p.rel(needed)} missing; run `xewe modules generate`", EXIT_NOT_SETUP)
    cli = cli_path(p, cfg)
    stem = p.sketch_ino().stem
    if p.root.name == stem:
        sketch_dir = p.root
    elif dry_run:
        sketch_dir = p.sketch_mirror(stem)
    else:
        sketch_dir = stage_sketch(p)
    argv = arduino.compile_argv(p.rel(cli), chip, p, sketch_dir)
    if dry_run:
        result(shlex.join(argv))
        if cfg is not None:
            env_vars = arduino.env(p, cfg.arduino_data(p))
            for key in sorted(k for k in env_vars if k.startswith("ARDUINO_")):
                log.debug("%s=%s", key, env_vars[key])
        return BuildResult(chip.name, True)

    assert cfg is not None
    name = project_name(p, lock)
    timestamp = _now()
    write_build_info(p, chip.name, build_info_header(name, version, timestamp, chip.name, defines))
    if clean:
        shutil.rmtree(p.cache_dir(chip.name), ignore_errors=True)
    out = p.out_dir(chip.name)
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    p.cache_dir(chip.name).mkdir(parents=True, exist_ok=True)

    result(f"build  {chip.name}  {chip.fqbn}")
    core = fetch.describe(cfg.installed.get("core")) if fetch.is_latest(lock.core.ref) else lock.core.ref
    result(f"       sketch {name} ({version})  modules {', '.join(_resolved_modules(p)) or '-'}  core {core}")
    start = time.monotonic()
    code, output = _compile(argv, arduino.env(p, cfg.arduino_data(p)), p.root, out / "compile.log")
    seconds = int(time.monotonic() - start)
    if code != 0:
        lines = [ln for ln in output.splitlines() if "error" in ln.lower()
                 and not re.search(r"Downloading index|Error initializing instance", ln)]
        for ln in lines[-15:]:
            log.error("%s", ln)
        result(f"FAIL   {chip.name}  {seconds} s  see {p.rel(out / 'compile.log')}")
        return BuildResult(chip.name, False, seconds=seconds)

    merged = p.cache_dir(chip.name) / f"{stem}.ino.merged.bin"
    if not merged.is_file():
        log.error("core did not produce %s", p.rel(merged))
        return BuildResult(chip.name, False, seconds=seconds)
    bin_name = binary_name(version, chip.name, name)
    shutil.copy2(merged, out / bin_name)
    (out / "manifest.json").write_text(
        MANIFEST_TEMPLATE.format(name=name, version=version, family=chip.family, binary=bin_name), encoding="utf-8"
    )
    size, percent = parse_size(output)
    warnings = sum(1 for ln in output.splitlines() if "warning:" in ln)
    rel_dir = f"{p.root.name}/{p.rel(out)}"
    installed = cfg.installed
    meta: dict[str, Any] = {
        "type": chip.name,
        "chip_family": chip.family,
        "project_name": name,
        "version": version,
        "timestamp_param": timestamp,
        "config": {k: typed(defines[k]) for k in sorted(defines)},
        "fqbn": chip.fqbn,
        "fqbn_extra": "",
        "compile_time_sec": seconds,
        "artifacts": {
            "binary_filename": bin_name,
            "path_rel_binary": f"{rel_dir}/{bin_name}",
            "path_rel_manifest_json": f"{rel_dir}/manifest.json",
            "path_rel_meta_json": f"{rel_dir}/meta.json",
        },
        "tools_version": __version__,
        "arduino_cli": installed.get("arduino_cli", ""),
        "esp32_core": installed.get("esp32", ""),
        "core_ref": installed.get("core", {}).get("ref", lock.core.ref),
        "modules_ref": installed.get("modules", {}).get("ref", lock.modules.ref),
        "modules": {"selected": lock.selected, "resolved": _resolved_modules(p)},
        "sketch_size": size,
        "sketch_size_percent": percent,
        "warnings": warnings,
    }
    (out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    (out / STAMP_NAME).write_text(build_key(chip.name, version, defines) + "\n", encoding="utf-8")
    size_text = f"Sketch uses {size} bytes" if size is not None else "size unknown"
    if size is not None and percent is not None:
        size_text += f" ({percent}%)"
    result(f"ok     {chip.name}  {seconds} s  {size_text}  {warnings} warnings")
    result(f"       {p.rel(out / bin_name)}")
    return BuildResult(chip.name, True, out / bin_name, seconds, size, warnings, percent)


def build(
    p: Paths, lock: Lock, chip_names: list[str], defines: dict[str, str], clean: bool = False, dry_run: bool = False
) -> int:
    """Build each chip in turn (continuing after a failure); exit 1 if any failed."""
    results = [build_chip(p, lock, c, defines, clean, dry_run=dry_run) for c in chip_names]
    if len(results) > 1 and not dry_run:
        result("")
        for r in results:
            status = "ok  " if r.ok else "FAIL"
            result(f"{status}  {r.chip}  {r.seconds} s")
    return EXIT_OK if all(r.ok for r in results) else EXIT_FAIL
