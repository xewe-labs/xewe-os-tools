def test_parse_size_from_compile_log(tmp_path: Path) -> None:
    log = tmp_path / "compile.log"
    log.write_text(
        "Using library XeWeCore at version 1.0.0 in folder: build/libraries/XeWeCore\n"
        "Sketch uses 223406 bytes (17%) of program storage space. Maximum is 1310720 bytes.\n"
        "Global variables use 13240 bytes (4%) of dynamic memory, leaving 314440 bytes for local variables.\n"
    )
    assert build.parse_size(log.read_text()) == (223406, 17)
    assert build.parse_size("Sketch uses 10 bytes of program storage space.\n") == (10, None)
    assert build.parse_size("no size here") == (None, None)


def test_build_key_covers_defines_version_chip() -> None:
    base = build.build_key("c3", "2.0.15", {"A": "1", "B": "2"})
    assert base == build.build_key("c3", "2.0.15", {"B": "2", "A": "1"})
    assert base != build.build_key("c3", "2.0.15", {"A": "1"})
    assert base != build.build_key("c3", "2.0.15", {"A": "1", "B": "3"})
    assert base != build.build_key("c3", "2.0.16", {"A": "1", "B": "2"})
    assert base != build.build_key("s3", "2.0.15", {"A": "1", "B": "2"})


