def test_sketch_staging_when_folder_differs(
    tmp_path: Path, project: Paths, monkeypatch: pytest.MonkeyPatch, fake_cli
) -> None:
    renamed = tmp_path / "my-firmware"
    shutil.move(str(project.root), str(renamed))
    monkeypatch.chdir(renamed)
    assert main(["build", "--chip", "c3"]) == 0
    staged = renamed / "build/tmp/sketch/xewe-os"
    assert (staged / "xewe-os.ino").is_file() and (staged / "src/Modules.h").is_file()
    assert (staged / "Config.h").stat().st_mtime == (renamed / "Config.h").stat().st_mtime
    assert not list(renamed.glob("my-firmware.ino"))
    assert (renamed / "build/builds/c3/out/2.0.15-c3-xewe-os.bin").is_file()
    assert (renamed / "build/builds/c3/cache/xewe-os.ino.merged.bin").is_file()
    argv = fake_cli()[-1]["argv"]
    assert argv[-1] == "build/tmp/sketch/xewe-os"
    # the -include names the build-path copy that arduino-cli makes of the staged sketch
    assert (
        f'-include "{Paths(renamed).cache_dir("c3") / "sketch" / "Config.h"}" -include '
        in argv[argv.index("--build-property") + 1]
    )


