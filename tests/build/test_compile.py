def test_compile_includes_config_h_everywhere(project: Paths, fake_cli) -> None:
    assert main(["build", "--chip", "c3"]) == 0
    argv = fake_cli()[-1]["argv"]
    prop = argv[argv.index("--build-property") + 1]
    gen = project.gen_dir("c3") / "XeWeBuildInfo" / "src"
    # build info (chip macro) first, then Config.h as arduino-cli copies it into the build path (the
    # file the sketch includes, so #pragma once skips the sketch's include), then the overrides
    config_h = project.cache_dir("c3") / "sketch" / "Config.h"
    assert prop == (
        f'compiler.cpp.extra_flags=-I "{gen}" -include "{gen / "XeWeBuildInfo.h"}" -include "{config_h}" '
        f'-include "{gen / "XeWeOverrides.h"}"'
    )
    assert argv.index("--build-property") < argv.index("--warnings")


