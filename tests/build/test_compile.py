SENTINEL_CONFIG_H = """#pragma once
// #define XEWE_LED_COUNT INJECTED_FROM_DOTENV
#define XEWE_LED_VOLTAGE INJECTED_FROM_DOTENV
  #  define XEWE_WIFI_SSID INJECTED_FROM_DOTENV  // from the dotenv file
"""


def _sentinel_project(project: Paths, env_text: str) -> Path:
    (project.root / "Config.h").write_text(SENTINEL_CONFIG_H)
    env_file = project.root.parent / "bench-env.txt"
    env_file.write_text(env_text)
    return env_file


def _build_info(project: Paths, chip: str = "c3") -> list[str]:
    """The lines of the overrides header (the injected and --define values)."""
    return (project.gen_dir(chip) / "XeWeBuildInfo/src/XeWeOverrides.h").read_text().splitlines()


def test_build_injects_dotenv_values(project: Paths, caplog: pytest.LogCaptureFixture) -> None:
    secret = 'Net "5" \\ GHz'
    env_file = _sentinel_project(project, f"XEWE_LED_VOLTAGE=12\nXEWE_WIFI_SSID='{secret}'\nXEWE_LED_COUNT=30\n")
    caplog.set_level("INFO", logger="xewe")
    assert main(["build", "--chip", "c3", "--env", str(env_file), "--define", "LED_PIN=8"]) == 0
    assert _build_info(project)[2:] == [
        "#undef XEWE_LED_VOLTAGE",
        "#define XEWE_LED_VOLTAGE 12",  # a number is written bare
        "#undef XEWE_WIFI_SSID",
        '#define XEWE_WIFI_SSID "Net \\"5\\" \\\\ GHz"',  # anything else as a C string literal
        "#undef LED_PIN",
        "#define LED_PIN 8",
    ]
    build_info = (project.gen_dir("c3") / "XeWeBuildInfo/src/XeWeBuildInfo.h").read_text()
    assert "XEWE_LED_VOLTAGE" not in build_info and "LED_PIN" not in build_info
    assert "injected from dotenv: XEWE_LED_VOLTAGE, XEWE_WIFI_SSID" in caplog.text
    assert secret not in caplog.text and "XEWE_LED_COUNT" not in caplog.text  # a commented line is not a sentinel
    meta = json.loads((project.out_dir("c3") / "meta.json").read_text())
    assert meta["config"] == {"LED_PIN": 8, "XEWE_LED_VOLTAGE": "(dotenv)", "XEWE_WIFI_SSID": "(dotenv)"}
    assert secret not in (project.out_dir("c3") / "meta.json").read_text()
    # the stamp covers the injected values: another value makes the image stale
    binary = project.out_dir("c3") / meta["artifacts"]["binary_filename"]
    stamp = (binary.parent / build.STAMP_NAME).read_text().strip()
    injected = {"XEWE_LED_VOLTAGE": "12", "XEWE_WIFI_SSID": build.dotenv.c_literal(secret)}
    assert stamp == build.build_key("c3", "2.0.15", {"LED_PIN": "8"}, "no_ota", injected)
    assert stamp != build.build_key("c3", "2.0.15", {"LED_PIN": "8"}, "no_ota", {**injected, "XEWE_LED_VOLTAGE": "5"})


def test_build_injection_precedence(project: Paths, monkeypatch: pytest.MonkeyPatch) -> None:
    env_file = _sentinel_project(project, "XEWE_LED_VOLTAGE=12\nXEWE_WIFI_SSID=FileNet\n")
    monkeypatch.setenv("XEWE_WIFI_SSID", "RealNet")  # the real environment wins over the file
    assert main(["build", "--chip", "c3", "--env", str(env_file), "--define", "XEWE_LED_VOLTAGE=24"]) == 0
    lines = _build_info(project)
    assert '#define XEWE_WIFI_SSID "RealNet"' in lines
    # a --define of the same name wins and the dotenv value is not written: no duplicate #define
    assert [ln for ln in lines if "XEWE_LED_VOLTAGE" in ln] == [
        "#undef XEWE_LED_VOLTAGE",
        "#define XEWE_LED_VOLTAGE 24",
    ]


