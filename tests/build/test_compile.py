    assert (project.gen_dir("s3") / "XeWeBuildInfo/library.properties").read_text().startswith("name=XeWeBuildInfo\n")
    meta = json.loads((project.out_dir("s3") / "meta.json").read_text())
    assert meta["config"] == {"LED_PIN": 8, "WIFI_SSID": '"net"'}


