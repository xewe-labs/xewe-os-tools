def test_modules_change_makes_build_stale(project: Paths) -> None:
    assert main(["build", "--chip", "c3"]) == 0
    binary = project.out_dir("c3") / "2.0.15-c3-xewe-os.bin"
    key = build.build_key("c3", "2.0.15", {})
    assert build.is_up_to_date(project, binary, key)
    header = project.modules / "src" / "Wifi" / "Wifi.h"
    os.utime(header, (binary.stat().st_mtime + 5, binary.stat().st_mtime + 5))
    assert not build.is_up_to_date(project, binary, key)


def test_sketch_staging_when_folder_differs(tmp_path: Path, project: Paths, monkeypatch: pytest.MonkeyPatch,
                                            fake_cli) -> None:
    renamed = tmp_path / "my-firmware"
    shutil.move(str(project.root), str(renamed))
    monkeypatch.chdir(renamed)
    assert main(["build", "--chip", "c3"]) == 0
    staged = renamed / "build/tmp/sketch/xewe-os"
    assert (staged / "xewe-os.ino").is_file() and (staged / "src/Modules.h").is_file()
    assert (staged / "Config.h").stat().st_mtime == (renamed / "Config.h").stat().st_mtime
    assert not list(renamed.glob("my-firmware.ino"))
    assert (renamed / "build/builds/c3/out/2.0.15-c3-xewe-os.bin").is_file()
    assert (renamed / "build/builds/c3/cache/xewe-os.ino.merged.bin").is_file()
    assert fake_cli()[-1]["argv"][-1] == "build/tmp/sketch/xewe-os"


def test_all_chips_continues_after_failure(project: Paths, monkeypatch: pytest.MonkeyPatch,
                                           capsys: pytest.CaptureFixture[str], fake_cli) -> None:
    monkeypatch.setenv("FAKE_ARDUINO_COMPILE_FAIL", "esp32c6")
    assert main(["build", "--all-chips"]) == 1
    boards = [c["argv"][2].split(":")[2] for c in fake_cli() if c["argv"][0] == "compile"]
    assert boards == ["esp32c3", "esp32c6", "esp32s3"]
    assert (project.out_dir("s3") / "2.0.15-s3-xewe-os.bin").is_file()
    out = capsys.readouterr()
    assert "FAIL  c6" in out.out and "does not name a type" in out.err


