def test_flash_reuses_the_injected_image_until_the_value_changes(project: Paths) -> None:
    from xewe.build import flash
    from xewe.modules import lockfile

    env_file = _sentinel_project(project, "XEWE_LED_VOLTAGE=12\nXEWE_WIFI_SSID=Net\n")
    os.environ["XEWE_ENV"] = str(env_file)
    lock = lockfile.load(project.lock)
    assert main(["build", "--chip", "c3"]) == 0
    assert flash.built_image(project, lock, "c3")[1] is True
    env_file.write_text("XEWE_LED_VOLTAGE=24\nXEWE_WIFI_SSID=Net\n")
    assert flash.built_image(project, lock, "c3")[1] is False
    env_file.write_text("XEWE_WIFI_SSID=Net\n")  # a missing value: stale, and the build names the key
    assert flash.built_image(project, lock, "c3")[1] is False


@pytest.mark.skipif(shutil.which("cpp") is None, reason="needs a C preprocessor (cpp)")
@pytest.mark.parametrize(
    ("config_line", "flags", "value"),
    [
        ("#define XEWE_LED_VOLTAGE INJECTED_FROM_DOTENV", [], "12"),  # a bare sentinel line
        ("#define XEWE_LED_VOLTAGE 7", ["--define", "XEWE_LED_VOLTAGE=9"], "9"),  # a bare value loses to --define
        ("#ifndef XEWE_LED_VOLTAGE\n#define XEWE_LED_VOLTAGE 7\n#endif", [], "7"),  # nothing overrides it
    ],
)
def test_overrides_win_over_config_h_without_warnings(
    project: Paths, fake_cli, tmp_path: Path, config_line: str, flags: list[str], value: str
) -> None:
    import shlex
    import subprocess

    (project.root / "Config.h").write_text(
        f"#pragma once\n#ifdef XEWE_CHIP_C3\n#define CHIP_SEEN 1\n#endif\n{config_line}\n"
    )
    env_file = tmp_path / "bench-env.txt"
    env_file.write_text("XEWE_LED_VOLTAGE=12\n")
    assert main(["build", "--chip", "c3", "--env", str(env_file), *flags]) == 0
    argv = fake_cli()[-1]["argv"]
    extra = argv[argv.index("--build-property") + 1].removeprefix("compiler.cpp.extra_flags=")
    # as arduino-cli does: the sketch is copied into <build path>/sketch/ and compiled from there,
    # and it includes Config.h itself (a no-op, the same file as the -include)
    copy = project.cache_dir("c3") / "sketch"
    copy.mkdir(parents=True, exist_ok=True)
    shutil.copy2(project.root / "Config.h", copy / "Config.h")
    unit = copy / "unit.cpp"
    unit.write_text('#include "Config.h"\nint v = XEWE_LED_VOLTAGE; int c = CHIP_SEEN;\n')
    proc = subprocess.run(["cpp", "-P", *shlex.split(extra), str(unit)], capture_output=True, text=True, check=False)
    assert proc.returncode == 0, proc.stderr
    assert proc.stderr == ""  # no "redefined" warning
    assert f"int v = {value}; int c = 1;" in proc.stdout  # Config.h saw the chip macro of the first header
