def test_override_precedence(p: Paths, ports: list[Port], monkeypatch: pytest.MonkeyPatch) -> None:
    ports += [Port("/dev/ttyACM0", 0x303A, 0x1001), Port("/dev/ttyUSB9", 0x2341, 0x0043)]
    boards.set_override(p, "/dev/ttyUSB9", "s3", clear=False)
    board = boards.select(p, probe=False)
    assert (board.port, board.chip, board.detected_by) == ("/dev/ttyUSB9", "s3", "override")
    monkeypatch.setenv("XEWE_PORT", "/dev/ttyACM0")
    assert boards.select(p, probe=False).port == "/dev/ttyACM0"
    assert boards.select(p, port="/dev/ttyUSB9", probe=False).port == "/dev/ttyUSB9"


def test_override_absent_from_system_means_scan(p: Paths, ports: list[Port]) -> None:
    boards.set_override(p, "/dev/ttyGONE", "c3", clear=False)
    assert boards.select(p) is None


def test_override_preserved_across_rewrites(p: Paths, ports: list[Port]) -> None:
    boards.set_override(p, "/dev/ttyACM0", "c3", clear=False)
    ports.append(Port("/dev/ttyACM1", 0x303A, 0x1001))
    boards.scan(p, probe=False)
    data = tomllib.loads(p.boards_toml.read_text())
    assert data["override"] == {"port": "/dev/ttyACM0", "chip": "c3"}
    assert p.boards_toml.read_text().startswith("# generated by xewe; [override] is yours and is kept")
    boards.set_override(p, None, None, clear=True)
    assert "override" not in tomllib.loads(p.boards_toml.read_text())


def test_resolve_chip_rule(monkeypatch: pytest.MonkeyPatch) -> None:
    board = boards.Board("/dev/x", chip="s3")
    assert boards.resolve_chip("c6", board, "c3") == "c6"
    assert boards.resolve_chip(None, board, "c3") == "s3"
    assert boards.resolve_chip(None, None, "c6") == "c6"
    assert boards.resolve_chip(None, boards.Board("/dev/x", chip="s2"), None) == "c3"
    monkeypatch.setenv("XEWE_CHIP", "s3")
    assert boards.resolve_chip(None, None, "c3") == "s3"


